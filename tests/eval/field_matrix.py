"""Generate docs/renter-search/FIELD_COVERAGE.md from the Core catalog fixture and the corpus.

  uv run --no-sync python -m tests.eval.field_matrix
"""
import json
from collections import defaultdict
from pathlib import Path

from tests.eval.corpus import CATALOG_PATH, field_codes, load

TARGET = Path(__file__).resolve().parents[2] / "docs" / "renter-search" / "FIELD_COVERAGE.md"
PG = "AiListingSearchPostgresTest"
V2 = "AiListingSearchV2Test"
SVC = "AiListingSearchServiceTest"
# source -> (how Core filters it before LIMIT, strongest evidence, tests)
SOURCES = {
    "listings": ("Column of the public listing row", "SQL truth on Postgres", f"{PG} (category, price); {SVC}.rejectsBulkFetchAndAppliesAllPredicatesBeforeBoundedLimit, retainsFalseBooleanAndRequiresPublishedListings"),
    "listing_addresses": ("Address row; ward/city use VietMap codes", "SQL truth on Postgres", f"{PG} (ward_id); AI test_listing_location_and_budget"),
    "listing_room_details": ("EXISTS on the room detail row", "SQL truth on Postgres", f"{PG} (room.restroom_type); {SVC}.publishesFieldsForAllSeedCategoriesAndLinkedData"),
    "listing_apartment_details": ("EXISTS on the apartment detail row", "Published in catalog; shared detail/EXISTS compiler, no field-specific SQL assertion", f"{SVC}.publishesFieldsForAllSeedCategoriesAndLinkedData"),
    "listing_house_details": ("EXISTS on the house detail row", "Published in catalog; shared detail/EXISTS compiler, no field-specific SQL assertion", f"{SVC}.publishesFieldsForAllSeedCategoriesAndLinkedData"),
    "listing_amenities": ("EXISTS / NOT EXISTS (missing is not false)", "SQL truth on Postgres", f"{PG} (amenity.ELEVATOR); {SVC}.missingAmenityUsesNotExistsRatherThanFalseColumnComparison"),
    "listing_custom_amenities": ("EXISTS on a custom amenity row", "Published in catalog; shared detail/EXISTS compiler, no field-specific SQL assertion", f"{SVC}.publishesFieldsForAllSeedCategoriesAndLinkedData"),
    "listing_policy_values": ("Same-row EXISTS; INTEGER policies use a guarded cast", "SQL truth on Postgres", f"{PG} (policy.depositRefundDays.value); {V2}.integerPolicyUsesGuardedCastOnTheSamePolicyRow; {SVC}.petPermissionUsesPolicyValueAndCannotMatchAnotherPoliciesRow"),
    "listing_charges": ("Conditions on one charge type share one row", "Compiler unit", f"{V2}.conditionsOnOneChargeTypeAreEvaluatedOnTheSameRow"),
    "listing_furnishing_assets": ("Same-row grouping; total_quantity sums matching rows; ordinal handover condition", "SQL truth on Postgres", f"{PG} (furnishing.BED.total_quantity); {V2}.furnishingQuantityAndConditionShareRowsAndUseOrdinalRanks, integerPoliciesAndEveryFurnishingCodeArePublishedWithMetadata"),
    "listing_media": ("EXISTS on a media row of that type", "Published in catalog; shared detail/EXISTS compiler, no field-specific SQL assertion", f"{SVC}.publishesFieldsForAllSeedCategoriesAndLinkedData"),
    "listing_viewing_days": ("EXISTS on a viewing day", "Published in catalog; shared detail/EXISTS compiler, no field-specific SQL assertion", f"{SVC}.publishesFieldsForAllSeedCategoriesAndLinkedData"),
    "listing_viewing_slots": ("EXISTS on a viewing slot", "Published in catalog; shared detail/EXISTS compiler, no field-specific SQL assertion", f"{SVC}.publishesFieldsForAllSeedCategoriesAndLinkedData"),
    "computed": ("SQL CASE on price_unit x context (occupants, kWh, m3, vehicles); unknown is counted, never matched", "SQL truth on Postgres (per-person path: unit only, seed has no PERSON_MONTH)", f"{PG} (rent unknown/context); {V2}.perPersonRentWithoutOccupantsIsUnknownAndReported, costTotalsMirrorTheEstimateRulesAndRejectInvalidContext"),
    "application": ("Display only; never a filter (unsupported HIGHLIGHTS)", "Catalog contract", "AiCatalogContractTest; AI test_listing_ask (unsupported needs)"),
}


def render() -> str:
    catalog = json.loads(CATALOG_PATH.read_text(encoding="utf-8"))
    corpus = load()
    used = defaultdict(list)
    for case in corpus["cases"]:
        for code in field_codes(case):
            used[code].append(case["id"])
    by_source = defaultdict(list)
    for field in catalog["fields"]:
        by_source[field["source"]].append(field)
    lines = [
        "# Renter search field coverage",
        "",
        f"Generated by `python -m tests.eval.field_matrix` from `tests/fixtures/core_catalog_v2.json` "
        f"(catalogVersion `{catalog['catalogVersion']}`, {len(catalog['fields'])} fields) and `tests/eval/renter_corpus_v1.json`. "
        "Do not edit by hand; `tests/eval/test_corpus.py` fails when this file is stale.",
        "",
        "Every field is filtered in the Core database before `LIMIT` through the versioned `POST /public/listings/ai/search` "
        "(`version: 2`). The AI planner receives the same catalog through `GET /public/listings/ai/catalog`; there is no "
        "per-field tool. \"SQL truth on Postgres\" means a Core test compares results with independent SQL on a temporary "
        "database loaded with the HCM seed; \"Compiler unit\" means the SQL shape is asserted without a database.",
        "",
        "## By data source",
        "",
        "| Source | Fields | Filtering in Core | Evidence | Tests |",
        "|---|---:|---|---|---|",
    ]
    for source, fields in by_source.items():
        how, level, tests = SOURCES[source]
        lines.append(f"| `{source}` | {len(fields)} | {how} | {level} | {tests} |")
    lines += ["", "Context fields (customer facts, never listing filters): " + ", ".join(f"`{c}`" for c in catalog["contextFields"]) + ".",
              "Sorts: " + ", ".join(f"`{s}`" for s in catalog["sorts"]) + ".",
              "Nearby kinds (stored POI links, no provider call on read): " + ", ".join(f"`{k['code']}`" for k in catalog["nearbyKinds"]) + ".",
              "Unsupported needs (reported as limitations, never filtered): " + ", ".join(f"`{u['code']}`" for u in catalog["unsupported"]) + ".",
              "", "## Every field", "",
              "| Field | Label | Kind | Role | Operators | Needs context | Corpus IDs |", "|---|---|---|---|---|---|---|"]
    for source, fields in by_source.items():
        for f in fields:
            ids = used.get(f["code"], [])
            shown = ", ".join(ids[:6]) + (f" (+{len(ids) - 6})" if len(ids) > 6 else "")
            lines.append(f"| `{f['code']}` | {f['label']} | {f['kind']} | {f['role']} | {' '.join(f['operators'])} | "
                         f"{' '.join(f.get('requiresContext') or []) or '-'} | {shown or '-'} |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(render(), encoding="utf-8")
    print(TARGET.relative_to(TARGET.parents[2]))
